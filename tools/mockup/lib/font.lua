M.faces = {
  big = { glyphs = BIG, w = 5, h = 7, advance = 6 },
  small = { glyphs = SMALL, w = 3, h = 5, advance = 4 },
}

function M.width(text, face)
  local f = M.faces[face]
  return #text * f.advance - 1
end

-- Draws text with `put(x, y, colour)`. `scale` (integer) is used only for
-- labels in documentation images, never in the game-resolution mockups.
-- opts: { color, shadow, highlight, scale }
function M.draw(put, text, x, y, face, opts)
  local f = M.faces[face]
  local scale = opts.scale or 1
  for i = 1, #text do
    local ch = text:sub(i, i)
    local g = f.glyphs[ch] or f.glyphs[ch:upper()]
    assert(g, "font: missing glyph '" .. ch .. "'")
    local gx = x + (i - 1) * f.advance * scale
    for gy = 0, f.h - 1 do
      local row = g[gy + 1]
      for k = 0, f.w - 1 do
        if row:sub(k + 1, k + 1) == "#" then
          for sy = 0, scale - 1 do
            for sx = 0, scale - 1 do
              local px, py = gx + k * scale + sx, y + gy * scale + sy
              if opts.shadow then
                put(px + scale, py + scale, opts.shadow, true)
              end
            end
          end
        end
      end
    end
    for gy = 0, f.h - 1 do
      local row = g[gy + 1]
      for k = 0, f.w - 1 do
        if row:sub(k + 1, k + 1) == "#" then
          local col = opts.color
          if opts.highlight and gy == 0 then
            col = opts.highlight
          end
          if opts.lowlight and gy == f.h - 1 then
            col = opts.lowlight
          end
          for sy = 0, scale - 1 do
            for sx = 0, scale - 1 do
              put(gx + k * scale + sx, y + gy * scale + sy, col, false)
            end
          end
        end
      end
    end
  end
end

return M

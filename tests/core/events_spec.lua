local events = require("src.core.events")

describe("core.events", function()
  it("drains events in push order and empties the queue", function()
    local q = events.new()
    q:push({ type = "a" })
    q:push({ type = "b", x = 1 })
    assert.are.equal(2, q:size())
    local items = q:drain()
    assert.are.same({ { type = "a" }, { type = "b", x = 1 } }, items)
    assert.are.equal(0, q:size())
    assert.are.same({}, q:drain())
  end)

  it("rejects events without a string type", function()
    local q = events.new()
    assert.has_error(function()
      q:push({ x = 1 })
    end)
    assert.has_error(function()
      q:push("hit")
    end)
  end)
end)
